// Deterministic generation from the repository's frozen HTTP contract.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { format } from 'prettier'
const schemas = JSON.parse(
  readFileSync(new URL('../../docs/mvp/contracts/openapi.json', import.meta.url), 'utf8'),
).components.schemas
function type(s) {
  if (s.$ref) return s.$ref.split('/').at(-1)
  if (s.anyOf?.some((x) => x.type || x.$ref)) return s.anyOf.map(type).join(' | ')
  if (s.enum) return s.enum.map((x) => JSON.stringify(x)).join(' | ')
  if (s.type === 'array') return `Array<${type(s.items)}>`
  if (s.type === 'object') {
    if (!s.properties) return 'Record<string, unknown>'
    return `{ ${Object.entries(s.properties)
      .map(([k, v]) => `${k}${s.required?.includes(k) ? '' : '?'}: ${type(v)}`)
      .join('; ')} }`
  }
  return (
    { string: 'string', integer: 'number', number: 'number', boolean: 'boolean', null: 'null' }[
      s.type
    ] ?? 'unknown'
  )
}
mkdirSync(new URL('../src/types', import.meta.url), { recursive: true })
writeFileSync(
  new URL('../src/types/generated.ts', import.meta.url),
  await format(
    '// Generated by npm run contracts. Do not edit.\n' +
      Object.entries(schemas)
        .map(([k, s]) => `export type ${k} = ${type(s)}\n`)
        .join(''),
    { parser: 'typescript', semi: false, singleQuote: true, printWidth: 100, trailingComma: 'all' },
  ),
)
